import { Ionicons } from '@expo/vector-icons';
import { useState } from 'react';
import { Pressable, ScrollView, StyleSheet, View } from 'react-native';
import Animated, { FadeIn, LinearTransition } from 'react-native-reanimated';
import { Screen, StackHeader } from '@/components/Screen';
import { T } from '@/components/ui';
import { colors, fonts, spacing } from '@/constants/theme';
import { haptic } from '@/utils/format';

const FAQ: { q: string; a: string }[] = [
  { q: 'Do I need an account?', a: 'No. You start with an anonymous identity (UNKNOWN #number) stored securely on your phone. Deleting the app or choosing “New anonymous identity” starts over.' },
  { q: 'Who can see my photos?', a: 'You decide in Identity & Privacy: everyone, only after a mutual reveal (default), or nobody.' },
  { q: 'How does Identity Reveal work?', a: 'In a chat, each of you chooses what to share (name, photos, social, about). Nothing is shown until both of you agree.' },
  { q: 'How is the Mystery Match score calculated?', a: 'It is calculated on the server: 42 + 11 per shared interest + 7 per shared language + 5 per shared conversation preference + 4 if you both show the same country, capped at 99. No random numbers.' },
  { q: 'Are AI characters real people?', a: 'No. They are fictional AI personalities, always marked with an AI badge. Replies are generated by an AI model on our server.' },
  { q: 'How private is People Nearby?', a: 'It is off until you turn it on. Only an approximate area is used (snapped to about 2 km), others only see a distance band, and turning it off erases your area.' },
  { q: 'What do PLUS and VIP add?', a: 'More daily matches, advanced filters, saved favorites, more AI messages, wider Nearby radius and, for VIP, priority in Discover, Super Connects and exclusive themes. Safety tools stay free.' },
  { q: 'How do I cancel a subscription?', a: 'In Google Play → Payments & subscriptions → Subscriptions, or from Premium → Manage in the app.' },
  { q: 'How do I delete my data?', a: 'Settings → Account & Security → Delete my data. Your profile, photos, posts, messages and connections are permanently deleted.' },
];

/** Help Center — frequently asked questions. */
export default function Help() {
  const [open, setOpen] = useState<number | null>(0);
  return (
    <Screen edges={['top', 'bottom']}>
      <StackHeader title="Help Center" />
      <ScrollView contentContainerStyle={{ padding: spacing.md, gap: 10, paddingBottom: 40 }}>
        {FAQ.map((f, i) => (
          <Animated.View key={f.q} layout={LinearTransition.springify().damping(20)} style={s.item}>
            <Pressable accessibilityRole="button" accessibilityState={{ expanded: open === i }} onPress={() => { haptic.tap(); setOpen(open === i ? null : i); }} style={s.q}>
              <T style={{ flex: 1, fontFamily: fonts.bold }}>{f.q}</T>
              <Ionicons name={open === i ? 'remove' : 'add'} size={20} color={colors.text} />
            </Pressable>
            {open === i && <Animated.View entering={FadeIn}><T color={colors.textSecondary} style={{ paddingHorizontal: 16, paddingBottom: 14 }}>{f.a}</T></Animated.View>}
          </Animated.View>
        ))}
      </ScrollView>
    </Screen>
  );
}

const s = StyleSheet.create({
  item: { borderRadius: 20, backgroundColor: colors.white, borderWidth: 1, borderColor: colors.border, overflow: 'hidden' },
  q: { flexDirection: 'row', alignItems: 'center', gap: 10, padding: 16 },
});
